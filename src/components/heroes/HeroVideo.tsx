"use client";

import { useEffect, useRef, useState } from "react";
import { videoFallbackSrc, videoPosterSrc } from "@/components/MediaAsset";

/**
 * The hero card stack's video card.
 *
 * A `MediaAsset` video is the right default everywhere else, but the front card
 * of the home hero is the page's LCP element, and the default branch had two
 * costs the audit flagged (mobile PSI, Oct 2026 — LCP 4.0 s, of which 1.69 s was
 * load delay and 0.86 s the download of a 91 kB poster for a ~190 px box):
 *
 *  1. `<video poster>` is fetched at Medium priority and, because it lives deep
 *     in the document, late. There is no `srcset` on a video poster, so the
 *     phone also got the full 720x1280 still. Here the still is a real `<img>`
 *     with `srcset`/`sizes` (variants generated by
 *     `scripts/gen-hero-poster-variants.py`), which the browser can preload —
 *     see the `<link rel="preload">` the parent emits for the front card.
 *  2. `autoPlay` + `preload="metadata"` made the 556 kB MP4 race the LCP paint.
 *     The sources are only armed once the page has loaded (or gone idle), and
 *     the video fades in over the still when it actually starts playing, so the
 *     card looks and moves exactly as before — just not before the LCP.
 *
 * The still is the visible layer until then, including on iOS in Low Power Mode
 * where autoplay never happens — the same reason the poster existed.
 */

/** Poster widths, mirroring scripts/gen-hero-poster-variants.py. */
const POSTER_WIDTHS = [450, 720];

/** The card box is ~190 CSS px on phones and ~240 px in the desktop stack. */
export const HERO_CARD_SIZES = "(min-width: 1024px) 240px, 190px";

export type PosterSet = { src: string; srcSet: string };

/**
 * The responsive poster for a video still, by filename convention.
 * Returns null when the still is not a `.webp` we can derive variants from.
 */
export function posterSet(poster: string | null | undefined): PosterSet | null {
  if (!poster || !poster.toLowerCase().endsWith(".webp")) return null;
  const stem = poster.slice(0, -".webp".length);
  return {
    src: `${stem}-p${POSTER_WIDTHS[POSTER_WIDTHS.length - 1]}.webp`,
    srcSet: POSTER_WIDTHS.map((width) => `${stem}-p${width}.webp ${width}w`).join(", "),
  };
}

export function HeroVideo({
  src,
  alt = "",
  className = "",
  width,
  height,
  priority = false,
}: {
  src: string;
  alt?: string;
  className?: string;
  width?: number;
  height?: number;
  /** Above-the-fold card: its still is the LCP candidate. */
  priority?: boolean;
}) {
  const poster = videoPosterSrc(src);
  const set = posterSet(poster);
  const universalSrc = videoFallbackSrc(src);
  const sources = universalSrc ? [universalSrc, src] : [src];

  /** A variant 404s (poster regenerated by the CMS and not re-derived) — fall back. */
  const [variantsMissing, setVariantsMissing] = useState(false);
  /** Sources are only armed after load/idle. */
  const [armed, setArmed] = useState(false);
  /** Cross-fade in once the video genuinely plays. */
  const [playing, setPlaying] = useState(false);
  const videoRef = useRef<HTMLVideoElement>(null);

  useEffect(() => {
    let cancelled = false;
    /** Browsers without requestIdleCallback get a short defer instead. */
    const idle = (run: () => void) => {
      const ric = (window as unknown as { requestIdleCallback?: (cb: () => void, o?: { timeout: number }) => void })
        .requestIdleCallback;
      if (ric) ric(run, { timeout: 1500 });
      else window.setTimeout(run, 300);
    };
    const start = () => {
      if (!cancelled) setArmed(true);
    };
    if (document.readyState === "complete") {
      idle(start);
    } else {
      window.addEventListener("load", () => idle(start), { once: true });
    }
    return () => {
      cancelled = true;
    };
  }, []);

  useEffect(() => {
    if (!armed) return;
    const video = videoRef.current;
    if (!video) return;
    const attempt = video.play();
    // Autoplay can still be refused (iOS Low Power Mode) — the still stays.
    if (attempt && typeof attempt.catch === "function") attempt.catch(() => {});
  }, [armed]);

  const still = variantsMissing || !set ? poster : set.src;

  return (
    <>
      {still && (
        <img
          src={still}
          srcSet={variantsMissing || !set ? undefined : set.srcSet}
          sizes={variantsMissing || !set ? undefined : HERO_CARD_SIZES}
          alt=""
          aria-hidden
          loading="eager"
          // React 19 hoists a preload for every eager <img>, carrying src/the
          // srcset + sizes and this hint — so the front card's still is the one
          // fetch that starts from <head>, at the size the device actually needs.
          fetchPriority={priority ? "high" : undefined}
          decoding="async"
          width={width}
          height={height}
          className={className}
          onError={() => setVariantsMissing(true)}
        />
      )}
      <video
        ref={videoRef}
        className={`${className} transition-opacity duration-500`}
        style={{ opacity: playing ? 1 : 0 }}
        width={width}
        height={height}
        autoPlay
        muted
        loop
        playsInline
        // Nothing but the still is fetched until the sources are armed.
        preload="none"
        // Deliberately no `poster`: a video poster has no srcset and would pull
        // the full-size still back in alongside the responsive one above.
        disableRemotePlayback
        aria-hidden={alt === "" ? true : undefined}
        aria-label={alt || undefined}
        onPlaying={() => setPlaying(true)}
      >
        {armed && sources.map((source) => <source key={source} src={source} type={source.endsWith(".webm") ? "video/webm" : "video/mp4"} />)}
      </video>
    </>
  );
}
